using System.Security.Cryptography;
using System.Text;
using StudioDesk.Core.Security;

// Build-time tool. Not shipped to users.
//   new-key  <keyFile>                      create a random data key (base64)
//   pack     <assetsDir> <outDir> <keyFile> encrypt each top-level folder of assets into <name>.sdpak
//   emit-key <keyFile> <out.cs>             generate the C# source that embeds the key (split into shares)
return args switch
{
    ["new-key", var keyFile] => NewKey(keyFile),
    ["pack", var assets, var outDir, var keyFile] => Pack(assets, outDir, ReadKey(keyFile)),
    ["emit-key", var keyFile, var outFile] => EmitKey(ReadKey(keyFile), outFile),
    _ => Usage(),
};

static int NewKey(string keyFile)
{
    if (File.Exists(keyFile)) { Console.Error.WriteLine($"{keyFile} already exists; refusing to overwrite."); return 1; }
    Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(keyFile))!);
    File.WriteAllText(keyFile, Convert.ToBase64String(RandomNumberGenerator.GetBytes(AesGcmCipher.KeySize)));
    Console.WriteLine($"New data key written to {keyFile}. Keep it secret and back it up.");
    return 0;
}

static byte[] ReadKey(string keyFile)
{
    var text = Environment.GetEnvironmentVariable("STUDIODESK_DATA_KEY");
    if (string.IsNullOrWhiteSpace(text))
    {
        if (!File.Exists(keyFile))
            throw new FileNotFoundException($"Data key not found at '{keyFile}'. Run: dotnet run --project tools/StudioDesk.Packer -- new-key secrets/data.key");
        text = File.ReadAllText(keyFile);
    }
    var key = Convert.FromBase64String(text.Trim());
    if (key.Length != AesGcmCipher.KeySize) throw new InvalidDataException("Data key must be 32 bytes.");
    return key;
}

static int Pack(string assetsDir, string outDir, byte[] key)
{
    Directory.CreateDirectory(outDir);
    foreach (var dir in Directory.GetDirectories(assetsDir))
    {
        var name = Path.GetFileName(dir);
        var pack = Path.Combine(outDir, name + DataPack.Extension);
        DataPack.Create(dir, pack, key);
        Console.WriteLine($"Packed {name} -> {pack} ({new FileInfo(pack).Length:N0} bytes)");
    }
    return 0;
}

static int EmitKey(byte[] key, string outFile)
{
    var shareA = RandomNumberGenerator.GetBytes(key.Length);
    var shareB = new byte[key.Length];
    for (var i = 0; i < key.Length; i++) shareB[i] = (byte)(key[i] ^ shareA[i]);

    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated/> Do not commit. Generated at build time from the secret data key.");
    sb.AppendLine("namespace StudioDesk.App.Generated;");
    sb.AppendLine("internal static class EmbeddedKeys");
    sb.AppendLine("{");
    sb.AppendLine($"    private static readonly byte[] A = [{string.Join(",", shareA)}];");
    sb.AppendLine($"    private static readonly byte[] B = [{string.Join(",", shareB)}];");
    sb.AppendLine("    internal static byte[] DataKey()");
    sb.AppendLine("    {");
    sb.AppendLine("        var k = new byte[A.Length];");
    sb.AppendLine("        for (var i = 0; i < k.Length; i++) k[i] = (byte)(A[i] ^ B[i]);");
    sb.AppendLine("        return k;");
    sb.AppendLine("    }");
    sb.AppendLine("}");

    Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outFile))!);
    File.WriteAllText(outFile, sb.ToString());
    return 0;
}

static int Usage()
{
    Console.Error.WriteLine("Usage: new-key <keyFile> | pack <assetsDir> <outDir> <keyFile> | emit-key <keyFile> <out.cs>");
    return 2;
}
